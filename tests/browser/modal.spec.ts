import { test, expect } from "@playwright/test";
test("QR dialog contains keyboard focus and restores it after Escape or the close button", async ({
  page,
}) => {
  await page.goto("/tests/browser/index.html");
  const trigger = page.getByRole("button", { name: "QR 열기" });
  const dialog = page.getByRole("dialog", { name: "QR 코드 로그인" });
  await trigger.focus();
  await page.keyboard.press("Enter");
  await expect(dialog.locator("svg").first()).toBeVisible();
  await trigger.evaluate((el) => el.focus());
  await expect(trigger).not.toBeFocused();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await trigger.click();
  await dialog
    .getByRole("button", { name: "닫기", exact: true })
    .first()
    .click();
  await expect(dialog).toHaveCount(0);
});
test("keeps failed generation silent and retries the same class after list refresh fails", async ({
  page,
}) => {
  const alerts: string[] = [];
  page.on("dialog", async (alert) => {
    alerts.push(alert.message());
    await alert.accept();
  });
  await page.addInitScript(() => {
    Object.assign(window, {
      sounds: 0,
      AudioContext: class {
        constructor() {
          (window as Window & { sounds: number }).sounds++;
        }
        createOscillator() {
          return {
            connect() {},
            frequency: { value: 0 },
            start() {},
            stop() {},
          };
        }
        createGain() {
          return {
            connect() {},
            gain: { setValueAtTime() {}, exponentialRampToValueAtTime() {} },
          };
        }
      },
    });
  });
  await page.goto("/tests/browser/index.html");
  await page.getByRole("button", { name: "새 수업 추가" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.locator("#name").fill("회귀 테스트");
  await dialog.locator("#clientId").selectOption("client");
  await dialog.locator("#managerId").selectOption("manager");
  await dialog.locator("#start_date").fill("2026-01-01");
  await dialog.locator('button[type="submit"]').click();
  await expect(
    dialog.getByText("응답 연결 끊김", { exact: true }),
  ).toBeVisible();
  await expect(page.getByText("최신 정보를 불러오지 못했습니다. 이전 내용을 표시하고 있습니다.")).toBeAttached();
  expect(alerts).toEqual([]);
  await expect(dialog.getByRole("alert")).toContainText("수업은 만들어졌습니다");
  const state = () =>
    page.evaluate(() => {
      const w = window as Window & {
        sounds: number;
        attempts: { classes: number; generations: { classId: string }[] };
      };
      return { sounds: w.sounds, ...w.attempts };
    });
  expect(await state()).toMatchObject({ sounds: 0, classes: 1 });
  await dialog.getByRole("button", { name: "게임 데이터 다시 생성" }).click();
  await expect(dialog).toHaveCount(0);
  const result = await state();
  expect(result).toMatchObject({ sounds: 1, classes: 1 });
  expect(result.generations).toHaveLength(2);
  expect(result.generations[1]).toEqual(result.generations[0]);
  expect(result.generations[0].classId).toBe("class-1");
});
for (const mode of ["stock without AI", "finance"] as const) {
  test(
    "creates a class without generating stocks: " + mode,
    async ({ page }) => {
      await page.goto("/tests/browser/index.html");
      await page.getByRole("button", { name: "새 수업 추가" }).click();
      const dialog = page.getByRole("dialog");
      await dialog.locator("#name").fill("기본 수업");
      await dialog.locator("#clientId").selectOption("client");
      await dialog.locator("#managerId").selectOption("manager");
      await dialog.locator("#start_date").fill("2026-01-01");
      if (mode === "finance")
        await dialog.locator('[value="finance_sim"]').check();
      else await dialog.locator("#autoGenerateData").uncheck();
      await dialog.locator('button[type="submit"]').click();
      await expect(dialog).toHaveCount(0);
      expect(
        await page.evaluate(
          () =>
            (
              window as Window & {
                attempts: { classes: number; generations: unknown[] };
              }
            ).attempts,
        ),
      ).toEqual({ classes: 1, generations: [] });
    },
  );
}
